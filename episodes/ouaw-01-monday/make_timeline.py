"""Ep 1 timeline: where each voice line starts (s) and the caption groups (1-3 words) in absolute time.
    python3 episodes/ouaw-01-monday/make_timeline.py   -> timeline.json (read by the composition), prints a table"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
W = json.load(open(os.path.join(HERE, "voice/words.json")))
FPS = 30
# line start times (s). Gaps are tight (0.15-0.25 s after the last word); reactions overlap.
START = dict(m1=0.70, c1=5.30, m2=7.35, c2=9.75, c3=13.85, c4=20.95, m3=26.15, c5=28.20, m4=34.55)
# caption groups: indices into the line's Whisper words; accent groups in the speaker colour. m1 word 0 is the groan.
GROUPS = dict(
    m1=[([1, 2], "I slept,", 0), ([3, 4, 5], "like, twelve hours", 0), ([6, 7], "this weekend.", 0), ([8, 9, 10], "Why am I", 0), ([11, 12], "SO TIRED?", 1)],
    c1=[([0, 1], "Because you", 0), ([2, 3, 4], "just flew in", 0), ([5, 6, 7], "from NEW YORK.", 2)],
    m2=[([0, 1], "I didn't", 0), ([2, 3], "go anywhere.", 0), ([4, 5], "I was", 0), ([6, 7], "in bed.", 0)],
    c2=[([0, 1], "Your body", 0), ([2, 3, 4], "thinks you did.", 0), ([5, 6], "It's called", 0), ([7, 8, 9], "SOCIAL JETLAG.", 2)],
    c3=[([0, 1], "On weekends", 0), ([2, 3], "you sleep", 0), ([4, 5, 6], "and wake up", 0), ([7, 8], "hours later,", 0), ([9, 10, 11], "so your body", 0),
        ([12, 13], "clock shifts.", 0), ([14, 15, 16], "Then MONDAY'S alarm", 1), ([17, 18], "drags it", 0), ([19, 20], "right back.", 0)],
    c4=[([0, 1], "Scientists say", 0), ([2, 3], "it's like", 0), ([4, 5], "flying west", 0), ([6, 7], "every Friday", 0), ([8, 9, 10], "and flying back", 0), ([11, 12], "every Sunday.", 0)],
    m3=[([0, 1], "Okay, okay.", 0), ([2, 3, 4], "How do I", 0), ([5, 6], "fix it?", 0)],
    c5=[([0, 1], "Two things.", 0), ([2, 3, 4], "Get MORNING LIGHT", 2), ([5, 6, 7], "as soon as", 0), ([8, 9, 10], "you wake up.", 0),
        ([11, 12], "And don't", 0), ([13, 14], "SLEEP IN", 2), ([15, 16], "too much", 0), ([17, 18], "on weekends.", 0)],
    m4=[([0], "Fine.", 0), ([1, 2], "This Saturday,", 0), ([3, 4], "I'm up", 0), ([5, 6], "at EIGHT.", 2)],
)
# accent: 0 none, 1 = last word(s) in caps are the accent, 2 = the CAPS words are the accent (same thing: CAPS = accent)
END = 46.0
def main():
    caps, lines = [], []
    for lid, st in START.items():
        L = W[lid]
        words = [dict(w=w["w"], s=round(st + w["s"], 3), e=round(st + w["e"], 3)) for w in L["words"] if not (lid == "m1" and w["w"].lower().startswith("ugh"))]
        lines.append(dict(id=lid, who=L["who"], start=st, dur=L["dur"], wav=f"ouaw01/voice/{lid}.wav", words=words))
        gs = GROUPS[lid]
        for gi, (idx, text, _) in enumerate(gs):
            heard = " ".join(L["words"][i]["w"] for i in idx).lower().replace("12", "twelve").replace("8", "eight").replace("jet lag", "jetlag")
            got, want = re.sub(r"[^a-z]", "", heard), re.sub(r"[^a-z]", "", text.lower())
            assert got == want, (lid, text, heard)
            s = st + L["words"][idx[0]]["s"]
            e = st + L["words"][idx[-1]]["e"]
            nxt = st + L["words"][gs[gi + 1][0][0]]["s"] if gi + 1 < len(gs) else e + 0.35
            accent = [w for w in re.findall(r"[A-Z']{2,}|\bSO\b", text)]
            caps.append(dict(line=lid, who=L["who"], text=text, accent=accent, s=round(s, 3), e=round(max(e, min(nxt, e + 0.35)), 3)))
    for a, b in zip(caps, caps[1:]):  # one pill at a time: a pill ends when the next one starts
        a["e"] = min(a["e"], b["s"])
    json.dump(dict(fps=FPS, end=END, frames=int(END * FPS), lines=lines, captions=caps), open(os.path.join(HERE, "timeline.json"), "w"), indent=1)
    # the composition reads a TS copy (no JSON imports in this project)
    ts = os.path.join(HERE, "../../src/series/onceuponawhy/episodes/ouaw01/timeline.ts")
    os.makedirs(os.path.dirname(ts), exist_ok=True)
    with open(ts, "w") as f:
        f.write("// GENERATED by episodes/ouaw-01-monday/make_timeline.py from the approved voice. Do not edit.\n")
        f.write("export const TL = " + json.dumps(dict(fps=FPS, end=END, frames=int(END * FPS), lines=lines, captions=caps), indent=1) + " as const;\n")
    for c in caps:
        print(f"{c['s']:6.2f}-{c['e']:6.2f} {c['who']:6s} {c['text']}")
main()
